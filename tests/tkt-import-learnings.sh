#!/usr/bin/env bash
# t-8a0d: a cloud session no longer runs learnings-sweep, so its PR carries no LEARNINGS.md row (that commit was the guaranteed conflict with
# main); `tkt import-results` adds the row here, from the imported .tickets/<id>/learnings.md. Prod path: the board's Import results button and
# `tkt import-results` -> _import_learnings_row (the call site is pinned in tests/cloud-round-trip.sh). One row at the top of the canon:learnings table,
# the stamp rewritten, nothing else touched, uncommitted; it adds nothing, and says why, when it cannot do that safely. Also pins the two
# instruction lines (complete.md step 8, docs/setup.md) that keep the row off a cloud PR.
set -euo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/helpers.sh"

W="$(mktemp -d "${TMPDIR:-/tmp}/tkt-import-learnings.XXXXXX")"
trap 'rm -rf "$W"' EXIT
export HOME="$W/home" TMPDIR="$W/tmp"; mkdir -p "$HOME" "$TMPDIR"

# the function under test, exactly as shipped (tkt is a script, not a library)
eval "$(sed -n '/^_import_learnings_row() {/,/^}/p' "$TKT")"   # (bash 3.2 cannot `source <(...)`)
declare -F _import_learnings_row >/dev/null || fail "_import_learnings_row not found in tkt"

STAMP_OLD="11-01-2026 09:00"
learn() { # learn <rows...>: a LEARNINGS.md the way learnings-sweep writes it
  printf '# Learnings\n\nlearnings-sweep last run: %s\n\n<!-- canon:learnings:BEGIN -->\n| Date | Ticket | Finding | Status |\n|---|---|---|---|\n' "$STAMP_OLD"
  printf '%s\n' "$@"
  printf '<!-- canon:learnings:END -->\n'
}
ROW_A='| 2026-11-03 | [t-0001](.tickets/t-0001/learnings.md) | older finding | UNPROMOTED |'
ROW_B='| 2026-10-30 | [t-0002](.tickets/t-0002/learnings.md) | oldest finding | PROMOTED → critique |'
candidate() { # candidate <id> <lessons-line|-> <body>  (the shape tkt learn writes)
  mkdir -p "$R/.tickets/$1"
  { printf -- '---\nticket: %s\ngenerated: 2026-11-07T19:32:38Z\nstatus: UNPROMOTED\n---\n# Learnings candidate — %s: a title\n\n> **UNPROMOTED.** Generated by `tkt learn`.\n\n' "$1" "$1"
    printf '## Deviations (plan vs actual)\n\n_none_\n\n## Evaluator findings\n\n%s\n\n## Candidate lessons\n' "$3"
    printf -- '- [ ] Lesson from the evaluator findings above\n- [ ] Lesson from the reviewer findings above\n'
    [[ "$2" == - ]] || printf -- '- [ ] %s\n' "$2"
    printf -- '- [ ] (other)\n'; } > "$R/.tickets/$1/learnings.md"
}
run() { # run <id>: prints the function's output; the project root is $R
  _import_learnings_row "$R" "$R/.tickets/$1" "$1" 2>&1
}
fresh() { R="$W/p$((++N))"; mkdir -p "$R"; learn "$ROW_A" "$ROW_B" > "$R/LEARNINGS.md"; cp "$R/LEARNINGS.md" "$R/LEARNINGS.orig"; }
N=0

# 1. a filled Candidate lessons item is the finding; the row is the first under the separator; only the stamp and that row change
fresh; candidate t-xxxx "Keep both rows" "No blocking findings."
out="$(run t-xxxx)"
assert_contains "$out" "added its LEARNINGS.md row for t-xxxx (uncommitted): Keep both rows"
ROW_NEW='| 2026-11-07 | [t-xxxx](.tickets/t-xxxx/learnings.md) | Keep both rows | UNPROMOTED |'
assert_eq "$ROW_NEW" "$(sed -n 8p "$R/LEARNINGS.md")"          # lines 1-7: title, blank, stamp, blank, BEGIN, header, separator
assert_eq "$ROW_A" "$(sed -n 9p "$R/LEARNINGS.md")"; assert_eq "$ROW_B" "$(sed -n 10p "$R/LEARNINGS.md")"
assert_eq 11 "$(wc -l < "$R/LEARNINGS.md" | tr -d ' ')"
assert_eq "2" "$(diff "$R/LEARNINGS.orig" "$R/LEARNINGS.md" | grep -c '^[<>]' | awk '{print ($1 - 1) / 2 + 1}')"   # stamp (1 changed pair) + the one new row
grep -qE '^learnings-sweep last run: [0-9]{2}-[0-9]{2}-[0-9]{4} [0-9]{2}:[0-9]{2}$' "$R/LEARNINGS.md" || fail "the stamp is not in the sweep's format"
[[ "$(sed -n 3p "$R/LEARNINGS.md")" != "learnings-sweep last run: $STAMP_OLD" ]] || fail "the stamp was not rewritten"
# a second import adds nothing
cp "$R/LEARNINGS.md" "$R/LEARNINGS.before"; out="$(run t-xxxx)"
assert_contains "$out" "no LEARNINGS.md row added: it already has a row for t-xxxx"
cmp -s "$R/LEARNINGS.before" "$R/LEARNINGS.md" || fail "a second import changed LEARNINGS.md"

# 2. no filled lesson: the first body line of the candidate (not the template lessons, the blockquote, the heading or _none_)
fresh; candidate t-yyyy - "No blocking findings. Non-blocking observations follow."
run t-yyyy >/dev/null
assert_eq '| 2026-11-07 | [t-yyyy](.tickets/t-yyyy/learnings.md) | No blocking findings. Non-blocking observations follow. | UNPROMOTED |' "$(sed -n 8p "$R/LEARNINGS.md")"

# 3. nothing to say: see learnings.md
fresh; candidate t-zzzz - "_none_"
run t-zzzz >/dev/null
assert_eq '| 2026-11-07 | [t-zzzz](.tickets/t-zzzz/learnings.md) | see learnings.md | UNPROMOTED |' "$(sed -n 8p "$R/LEARNINGS.md")"

# 4. a | in the finding would break the table: removed; a long finding is cut at 200 characters
fresh; candidate t-pipe "a | b" "x"
run t-pipe >/dev/null; assert_contains "$(sed -n 8p "$R/LEARNINGS.md")" "| a b | UNPROMOTED |"
fresh; LONG="$(printf 'w%.0s' $(seq 1 250))"; candidate t-long "$LONG" "x"
run t-long >/dev/null; f="$(sed -n 8p "$R/LEARNINGS.md" | awk -F' [|] ' '{print $3}')"; assert_eq 200 "${#f}"

# 5. refusals: each says why on one line and leaves LEARNINGS.md byte-identical
refused() { # refused <why> : expects the output and an unchanged file
  assert_contains "$out" "no LEARNINGS.md row added: $1"
  cmp -s "$R/LEARNINGS.orig" "$R/LEARNINGS.md" || fail "refusal ($1) still changed LEARNINGS.md"
}
fresh; candidate t-one1 "x" "x"; rm "$R/.tickets/t-one1/learnings.md"; out="$(run t-one1)"; refused "t-one1 has no learnings.md"
fresh; candidate t-two2 "x" "x"; rm "$R/LEARNINGS.md"; out="$(run t-two2)"; assert_contains "$out" "no LEARNINGS.md row added: there is no LEARNINGS.md here"
fresh; candidate t-thr3 "x" "x"; mv "$R/LEARNINGS.md" "$R/real.md"; ln -s real.md "$R/LEARNINGS.md"; out="$(run t-thr3)"
assert_contains "$out" "no LEARNINGS.md row added: LEARNINGS.md is a symlink"; cmp -s "$R/LEARNINGS.orig" "$R/real.md" || fail "a symlinked LEARNINGS.md's target was written"
fresh; candidate t-fou4 "x" "x"; sed -i.bak 's/^<!-- canon:learnings:END -->$/<!-- canon:learnings:BEGIN -->\n<!-- canon:learnings:END -->/' "$R/LEARNINGS.md"; rm "$R/LEARNINGS.md.bak"
cp "$R/LEARNINGS.md" "$R/LEARNINGS.orig"; out="$(run t-fou4)"; refused "LEARNINGS.md has no single canon:learnings table"      # two BEGIN markers
fresh; candidate t-fiv5 "x" "x"; grep -v '^|---' "$R/LEARNINGS.md" > "$R/x" && mv "$R/x" "$R/LEARNINGS.md"
cp "$R/LEARNINGS.md" "$R/LEARNINGS.orig"; out="$(run t-fiv5)"; refused "LEARNINGS.md has no single canon:learnings table"      # no separator row
fresh; candidate t-six6 "x" "x"; grep -v 'canon:learnings:END' "$R/LEARNINGS.md" > "$R/x" && mv "$R/x" "$R/LEARNINGS.md"
cp "$R/LEARNINGS.md" "$R/LEARNINGS.orig"; out="$(run t-six6)"; refused "LEARNINGS.md has no single canon:learnings table"      # no END marker

# 6. the two instruction lines that keep the row off a cloud PR (a prompt edit: the evaluator reads the wording, this pins that it exists)
grep -qi "runs: github" "$ROOT/skills/sprint/reference/complete.md" && grep -qi "does not run the .learnings-sweep" "$ROOT/skills/sprint/reference/complete.md" \
  || fail "complete.md step 8 does not say a cloud (runs: github) ticket skips learnings-sweep"
grep -qi "learnings-sweep" "$ROOT/docs/setup.md" || fail "docs/setup.md does not say a cloud session skips learnings-sweep"
echo "tkt-import-learnings: ok"
